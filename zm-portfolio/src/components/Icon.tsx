export type IconName = keyof typeof paths | keyof typeof strokes;

export function Icon({ name, size = 18, className, title }: { name: string; size?: number; className?: string; title?: string }) {
  const fill = paths[name];
  const stroke = strokes[name] ?? strokes.link;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      className={className}
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      focusable="false"
    >
      {title && <title>{title}</title>}
      {fill ? (
        <path d={fill} fill="currentColor" />
      ) : (
        <path d={stroke} fill="none" stroke="currentColor" strokeWidth={1.6} strokeLinecap="round" strokeLinejoin="round" />
      )}
    </svg>
  );
}

/** Map a social platform name to an icon key. */
export function platformIcon(platform: string, icon?: string | null) {
  const k = (icon || platform || '').toLowerCase().trim();
  if (k.includes('github')) return 'github';
  if (k.includes('linkedin')) return 'linkedin';
  if (k.includes('whatsapp')) return 'whatsapp';
  if (k.includes('insta')) return 'instagram';
  if (k.includes('facebook')) return 'facebook';
  if (k === 'x' || k.includes('twitter')) return 'x';
  if (k.includes('youtube')) return 'youtube';
  if (k.includes('mail')) return 'mail';
  if (k.includes('phone')) return 'phone';
  if (k.includes('web') || k.includes('site') || k.includes('portfolio')) return 'globe';
  return 'link';
}
